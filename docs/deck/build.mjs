#!/usr/bin/env node
/**
 * Builds docs/deck/deck.html: the talk as one page that opens in any browser.
 *
 *   pnpm deck           rebuild it from project/
 *   pnpm deck --check   fail if it is out of date (the unit suite runs this)
 *
 * The source of truth is project/: deck.json (the order, sections and fonts)
 * and one slides/<id>.html per slide, in the claude.ai Slides format. Those are
 * the same files the Slides artifact holds, so a change made here can be
 * published back there and one made there can be pulled here, file for file
 * (docs/deck/README.md). This page is only a way to see them without it.
 *
 * The format is plain HTML on a 1920×1080 canvas with inline styles, plus two
 * things a browser does not draw on its own: `<x-icon>`, replaced here with
 * inline SVG, and `<aside>`, the speaker notes, shown in a panel on N.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))

/**
 * The icons the deck uses, as 24×24 stroke paths. An icon the deck starts
 * using that is not here is drawn as a circle, and the check below names it.
 */
const ICONS = {
  Play: '<path d="M7 4l12 8-12 8z" fill="currentColor" stroke="none"/>',
  Link: '<path d="M10 14a5 5 0 0 0 7 0l3-3a5 5 0 0 0-7-7l-1 1"/><path d="M14 10a5 5 0 0 0-7 0l-3 3a5 5 0 0 0 7 7l1-1"/>',
  Lightning: '<path d="M13 2L4 14h7l-1 8 9-12h-7z"/>',
  Warning: '<path d="M12 3l10 18H2z"/><path d="M12 10v5"/><path d="M12 18h.01"/>',
  Activity: '<path d="M2 12h4l3-8 6 16 3-8h4"/>',
  Lightbulb: '<path d="M9 18h6"/><path d="M10 22h4"/><path d="M12 2a7 7 0 0 0-4 12.7c.6.5 1 1.3 1 2.3h6c0-1 .4-1.8 1-2.3A7 7 0 0 0 12 2z"/>',
  Users: '<circle cx="9" cy="8" r="4"/><path d="M2 21a7 7 0 0 1 14 0"/><path d="M16 4a4 4 0 0 1 0 8"/><path d="M22 21a7 7 0 0 0-5-6.7"/>',
  Wrench: '<path d="M14.7 6.3a4 4 0 0 0-5.4 5.4L3 18l3 3 6.3-6.3a4 4 0 0 0 5.4-5.4l-2.5 2.5-2.4-.6-.6-2.4z"/>',
}

const escapeHtml = (text) =>
  text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

function icon(name, style) {
  const body = ICONS[name] ?? '<circle cx="12" cy="12" r="9"/>'
  return (
    `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" ` +
    `stroke-linecap="round" stroke-linejoin="round" style="${style}; flex:none" aria-label="${name}">${body}</svg>`
  )
}

export function buildDeck() {
  const deck = JSON.parse(readFileSync(join(here, 'project/deck.json'), 'utf8'))
  const missingIcons = new Set()

  const slides = deck.order.map((id) => {
    let html = readFileSync(join(here, 'project/slides', `${id}.html`), 'utf8').trim()
    const notes = html.match(/<aside>([\s\S]*?)<\/aside>/)?.[1]?.trim() ?? ''
    html = html.replace(/<aside>[\s\S]*?<\/aside>\s*/, '')
    html = html.replace(
      /<x-icon name="([^"]*)"(?: style="([^"]*)")?><\/x-icon>/g,
      (_, name, style = '') => {
        if (!ICONS[name]) missingIcons.add(name)
        return icon(name, style)
      },
    )
    return { id, html, notes }
  })

  const fonts = Object.values(deck.faces ?? {})
    .filter((face) => face.href)
    .map((face) => `<link rel="stylesheet" href="${face.href}">`)
    .join('\n')

  const page = `<!doctype html>
<!-- Generated by docs/deck/build.mjs from docs/deck/project/. Edit those, then run pnpm deck. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(deck.title)}</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
${fonts}
<style>
  html, body { margin: 0; height: 100%; background: #0b0e0f; overflow: hidden; }
  .stage { position: fixed; inset: 0; display: grid; place-items: center; }
  .slide { position: absolute; width: 1920px; height: 1080px; transform-origin: center; display: none; }
  .slide.is-current { display: block; }
  .slide > section { position: relative; width: 1920px; height: 1080px; box-sizing: border-box; overflow: hidden; }
  .slide * { margin: 0; box-sizing: border-box; }
  .slide ul, .slide ol { padding-left: 1.2em; }
  .slide table { border-collapse: collapse; }
  .slide th, .slide td { padding: 0.35em 0.5em; border-bottom: 1px solid rgba(127,127,127,0.3); vertical-align: top; }
  .slide th { font-weight: 600; }
  .bar { position: fixed; left: 0; right: 0; bottom: 0; display: flex; gap: 16px; align-items: center;
    padding: 8px 16px; font: 13px/1.4 system-ui, sans-serif; color: #9aa6a4; background: rgba(11,14,15,0.85);
    opacity: 0; transition: opacity .2s; }
  body:hover .bar, .bar:focus-within { opacity: 1; }
  .bar button { font: inherit; color: inherit; background: none; border: 1px solid #2b3538; border-radius: 4px; padding: 2px 10px; cursor: pointer; }
  .notes { position: fixed; right: 0; top: 0; bottom: 0; width: min(520px, 90vw); padding: 24px 24px 64px; overflow: auto;
    font: 16px/1.55 system-ui, sans-serif; color: #d9e0df; background: #14191a; border-left: 1px solid #2b3538;
    white-space: pre-wrap; display: none; }
  body.show-notes .notes { display: block; }
  @media print {
    @page { size: 1920px 1080px; margin: 0; }
    html, body { overflow: visible; height: auto; background: none; }
    .stage { position: static; display: block; }
    .slide { position: relative; display: block !important; transform: none !important; page-break-after: always; }
    .bar, .notes { display: none !important; }
  }
</style>
</head>
<body>
<div class="stage">
${slides.map((s) => `<div class="slide" data-id="${s.id}">\n${s.html}\n</div>`).join('\n')}
</div>
<div class="notes" aria-live="polite"></div>
<div class="bar">
  <button type="button" data-go="-1" aria-label="Previous slide">←</button>
  <span class="count"></span>
  <button type="button" data-go="1" aria-label="Next slide">→</button>
  <button type="button" data-notes>Notes (N)</button>
  <span>F full screen · Ctrl/Cmd+P for a PDF, one slide a page</span>
</div>
<script>
const NOTES = ${JSON.stringify(Object.fromEntries(slides.map((s) => [s.id, s.notes]))).replace(/</g, '\\u003c')};
const slides = [...document.querySelectorAll('.slide')];
const ids = slides.map((s) => s.dataset.id);
let at = Math.max(0, ids.indexOf(location.hash.slice(1)));

function fit() {
  const scale = Math.min(innerWidth / 1920, innerHeight / 1080);
  for (const s of slides) s.style.transform = 'scale(' + scale + ')';
}
function show(i) {
  at = Math.min(slides.length - 1, Math.max(0, i));
  slides.forEach((s, n) => s.classList.toggle('is-current', n === at));
  document.querySelector('.count').textContent = (at + 1) + ' / ' + slides.length + ' · ' + ids[at];
  document.querySelector('.notes').textContent = NOTES[ids[at]] || '(no notes)';
  history.replaceState(null, '', '#' + ids[at]);
}
addEventListener('keydown', (e) => {
  if (e.metaKey || e.ctrlKey || e.altKey) return;
  if (['ArrowRight', 'PageDown', ' '].includes(e.key)) show(at + 1);
  else if (['ArrowLeft', 'PageUp'].includes(e.key)) show(at - 1);
  else if (e.key === 'Home') show(0);
  else if (e.key === 'End') show(slides.length - 1);
  else if (e.key === 'n' || e.key === 'N') document.body.classList.toggle('show-notes');
  else if (e.key === 'f' || e.key === 'F') document.fullscreenElement ? document.exitFullscreen() : document.documentElement.requestFullscreen();
  else return;
  e.preventDefault();
});
document.querySelectorAll('[data-go]').forEach((b) => b.addEventListener('click', () => show(at + Number(b.dataset.go))));
document.querySelector('[data-notes]').addEventListener('click', () => document.body.classList.toggle('show-notes'));
addEventListener('resize', fit);
addEventListener('hashchange', () => show(Math.max(0, ids.indexOf(location.hash.slice(1)))));
fit();
show(at);
</script>
</body>
</html>
`
  return { page, missingIcons: [...missingIcons], slides: slides.length }
}

const out = join(here, 'deck.html')

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { page, missingIcons, slides } = buildDeck()
  if (missingIcons.length > 0) {
    console.error(`No drawing for icon(s): ${missingIcons.join(', ')}. Add them to ICONS in build.mjs.`)
    process.exit(1)
  }
  if (process.argv.includes('--check')) {
    const current = readFileSync(out, 'utf8')
    if (current !== page) {
      console.error('docs/deck/deck.html is out of date with docs/deck/project/. Run pnpm deck.')
      process.exit(1)
    }
    console.log(`deck.html is up to date (${slides} slides)`)
  } else {
    writeFileSync(out, page)
    console.log(`Wrote docs/deck/deck.html (${slides} slides)`)
  }
}
